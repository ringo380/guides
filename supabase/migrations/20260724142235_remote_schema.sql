GRANT ALL ON public.runbook_progress TO authenticated;
GRANT ALL ON public.runbook_progress TO service_role;
CREATE INDEX idx_runbook_progress_user_id ON public.runbook_progress (user_id);
CREATE POLICY "Users insert own progress" ON public.runbook_progress FOR INSERT TO authenticated WITH CHECK ((auth.uid() = user_id));
CREATE POLICY "Users read own progress" ON public.runbook_progress FOR SELECT TO authenticated USING ((auth.uid() = user_id));
CREATE POLICY "Users update own progress" ON public.runbook_progress FOR UPDATE TO authenticated USING ((auth.uid() = user_id)) WITH CHECK ((auth.uid() = user_id));
