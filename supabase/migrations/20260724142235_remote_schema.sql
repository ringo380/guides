ALTER TABLE public.runbook_progress ADD CONSTRAINT runbook_progress_pkey PRIMARY KEY (id);
ALTER TABLE public.runbook_progress ADD CONSTRAINT runbook_progress_user_id_fkey FOREIGN KEY (user_id) REFERENCES auth.users(id) ON DELETE CASCADE;
ALTER TABLE public.runbook_progress ADD CONSTRAINT runbook_progress_user_id_key UNIQUE (user_id);
