CREATE TABLE public.runbook_progress (id uuid DEFAULT gen_random_uuid() NOT NULL, user_id uuid NOT NULL, progress jsonb DEFAULT '{}'::jsonb NOT NULL, updated_at timestamp with time zone DEFAULT now() NOT NULL);
